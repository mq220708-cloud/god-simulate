const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/shared/simulation-effects.js'), 'utf8');
const context = {};
vm.runInNewContext(source, context);
const bus = context.ThanhGioiSimulationEffects;
const seen = [];
const off = bus.subscribe(effect => seen.push(effect));
bus.emit({ type: 'notification', html: 'hello' });
assert.equal(seen.length, 1);
assert.equal(seen[0].type, 'notification');
assert.equal(bus.listenerCount(), 1);
off();
assert.equal(bus.listenerCount(), 0);
bus.emit({ type: 'roleplay-game-over', message: 'ended' });
assert.equal(seen.length, 1);
assert.throws(() => bus.subscribe(null), /listener/);
assert.throws(() => bus.emit({}), /typed/);
console.log('simulation-effects tests passed');
