const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/shared/world-context.js'), 'utf8');
const context = {};
vm.runInNewContext(source, context);
const world = context.ThanhGioiWorldContext();
assert.equal(world.isAttached(), false);
assert.throws(() => world.getState(), /not been attached/);
const state = {
  n: 2, c: 10, cfg: {}, T: new Uint8Array(4), O: new Uint16Array(4),
  X: new Uint8Array(4), RV: new Uint8Array(4), W: { ks: [] },
  CD: {}, BL: [], RD: []
};
assert.equal(world.attach(state), 1);
assert.equal(world.isAttached(), true);
assert.equal(world.getState(), state);
assert.equal(world.read('W'), state.W);
state.W.ks.push({ id: 1, name: 'Test', econ: { cash: 35, oil: 0, industry: 1, gdp: 0, unemployment: 8, exports: 0 } });
assert.equal(world.getKingdom(1), state.W.ks[0]);
assert.equal(world.getKingdom(0), undefined);
assert.equal(world.getKingdom('invalid'), undefined);
state.W.ks[0].pop = 10;
assert.equal(world.setKingdomStat(1, 'pop', 12.5), 12.5);
assert.equal(state.W.ks[0].pop, 12.5);
assert.equal(world.setKingdomStat(1, 'army', 3), 3);
assert.equal(world.setKingdomStat(1, 'loy', 55), 55);
assert.equal(state.W.ks[0].army, 3);
assert.equal(state.W.ks[0].loy, 55);
assert.equal(world.setEconomyStat(1, 'cash', 42), 42);
assert.equal(world.setEconomyStat(1, 'oil', 3.5), 3.5);
assert.equal(world.setEconomyStat(1, 'monthlyIncome', 1.25), 1.25);
assert.equal(state.W.ks[0].econ.cash, 42);
assert.equal(state.W.ks[0].econ.oil, 3.5);
assert.equal(state.W.ks[0].econ.monthlyIncome, 1.25);
assert.throws(() => world.setEconomyStat(99, 'cash', 1), /does not exist/);
assert.throws(() => world.setEconomyStat(1, 'unknown', 1), /supported numeric stat/);
assert.throws(() => world.setEconomyStat(1, 'cash', Infinity), /finite/);
assert.throws(() => world.setKingdomStat(99, 'pop', 1), /does not exist/);
assert.throws(() => world.setKingdomStat(1, 'missing', 1), /numeric stat/);
assert.throws(() => world.setKingdomStat(1, 'pop', Infinity), /finite/);
assert.equal(world.getKingdoms(), state.W.ks);
assert.deepEqual(Array.from(world.getLivingKingdoms(), k => k.id), [1]);
assert.equal(world.getTerrain(0), 0);
assert.equal(world.getTerrainVariant(0), 0);
assert.equal(world.hasRiver(0), false);
world.setTerrain(0, 4, 2, 1);
assert.equal(world.getTerrain(0), 4);
assert.equal(world.getTerrainVariant(0), 2);
assert.equal(world.hasRiver(0), true);
world.setOwner(0, 1);
world.setTerrain(0, 1, 0, 0);
assert.equal(world.getOwner(0), 0);
assert.throws(() => world.setTerrain(9, 3), /out of range/);
assert.throws(() => world.setTerrain(0, 7), /0 to 6/);
assert.equal(world.getOwner(0), 0);
assert.equal(world.setOwner(0, 1), 1);
assert.equal(world.getOwner(0), 1);
assert.equal(world.setOwner(0, 0), 0);
assert.equal(world.getOwner(0), 0);
assert.equal(world.getOwner(9), 0);
assert.throws(() => world.setOwner(9, 1), /out of range/);
assert.throws(() => world.setOwner(0, -1), /non-negative integer/);
assert.throws(() => world.setOwner(0, 1.5), /non-negative integer/);
const building = { t: 'farm', i: 1, c: 1, h: 100, p: 0, n: 8 };
assert.equal(world.getBuildings(), state.BL);
assert.equal(world.addBuilding(building), building);
assert.equal(world.getBuildings().length, 1);
assert.equal(world.removeBuilding(building), true);
assert.equal(world.removeBuilding(building), false);
world.addBuilding(building);
assert.equal(world.removeBuildingsAt(1), 1);
assert.equal(world.getBuildings().length, 0);
assert.throws(() => world.addBuilding({ t: 'farm', i: 9 }), /valid building/);
assert.throws(() => world.removeBuildingsAt(9), /out of range/);
assert.throws(() => world.replaceBuildings({}), /array/);
world.replaceBuildings([building]);
assert.equal(world.getBuildings()[0], building);
assert.equal(world.getResource(0), 0);
assert.equal(world.setResource(0, 120), 120);
assert.equal(world.getResource(0), 120);
assert.equal(world.adjustResource(0, -20), 100);
assert.equal(world.getResource(0), 100);
assert.throws(() => world.setResource(9, 1), /out of range/);
assert.throws(() => world.setResource(0, NaN), /finite/);
assert.throws(() => world.adjustResource(0, Infinity), /finite/);
state.W.ks.push({ id: 2, alive: 0 });
assert.deepEqual(Array.from(world.getLivingKingdoms(), k => k.id), [1]);
const nextW = { ks: [{ id: 1 }] };
assert.equal(world.write('W', nextW), 2);
assert.equal(world.read('W'), nextW);
assert.equal(world.getRevision(), 22);
assert.throws(() => world.attach({}), /missing/);
assert.throws(() => world.attach({ ...state, n: 3 }), /dimensions/);
assert.throws(() => world.read('missing'), /Unknown/);
assert.throws(() => world.write('missing', 1), /Unknown/);
console.log('world-context tests passed');
